#!/usr/bin/env node
/*
 * build-fonts.js: writes deck/theme/fonts.css with every font embedded as a
 * base64 data URI, so the deck's fonts load from file:// in every browser
 * (some browsers refuse to read a font file from disk next to a page that was
 * opened by double-click; a data URI always works) and so the single-file
 * build needs nothing else.
 *
 *     node tools/build-fonts.js            write deck/theme/fonts.css
 *     node tools/build-fonts.js --check    exit 1 if fonts.css is out of date
 *
 * Sources are the two variable woff2 files in deck/theme/fonts/. Both are
 * the "latin" subsets and both are licensed under the SIL Open Font License
 * 1.1, which allows embedding and redistribution:
 *
 *   Archivo   (c) The Archivo Project Authors (Omnibus-Type)   OFL 1.1
 *             axes used: wght 100-900, wdth 62-125. Upright only.
 *   Fraunces  (c) The Fraunces Project Authors                 OFL 1.1
 *             italic only. Axes used: wght, opsz, SOFT, WONK.
 *
 * WONK IS PINNED OFF IN THE FACE. The Fraunces file's own default is WONK 1
 * (the swash h, b, d, l, w), which docs/DIRECTION.md Part 1 section 4 forbids.
 * DOM text can switch it off with font-variation-settings, but a canvas
 * cannot set a variation axis at all, so canvas text (THEME.draw.label with
 * kind 'voice', the cost scene's deadpan line) would come out in the swash
 * forms and the deck would have two different italics. The @font-face rule
 * therefore carries font-variation-settings itself: every use of the family,
 * canvas included, starts from opsz 72, SOFT 0, WONK 0. An element's own
 * font-variation-settings still wins, axis by axis (the huge italic sets
 * opsz 144). node tools/check-theme.js fails if this line goes missing.
 * (A browser that ignores the descriptor still gets clean DOM text; only its
 * canvas italics fall back to the swash forms. Chromium honours it.)
 *
 * Only these two files are embedded: the deck uses no other weight files, no
 * upright Fraunces and no italic Archivo. The result must stay under 1.5 MB.
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.resolve(__dirname, '..');
var FONT_DIR = path.join(ROOT, 'deck', 'theme', 'fonts');
var OUT = path.join(ROOT, 'deck', 'theme', 'fonts.css');
var LIMIT = 1.5 * 1024 * 1024;

var FACES = [
  {
    file: 'archivo-latin-standard-normal.woff2',
    family: 'Archivo',
    licence: 'Archivo, (c) The Archivo Project Authors. SIL Open Font License 1.1.',
    css: [
      'font-style: normal;',
      'font-weight: 100 900;',
      'font-stretch: 62% 125%;',
      'font-display: block;'
    ]
  },
  {
    file: 'fraunces-latin-full-italic.woff2',
    family: 'Fraunces',
    licence: 'Fraunces Italic, (c) The Fraunces Project Authors. SIL Open Font License 1.1.',
    css: [
      'font-style: italic;',
      'font-weight: 100 900;',
      'font-display: block;',
      // keep in step with --voice-settings in deck/theme/tokens.css
      'font-variation-settings: "opsz" 72, "SOFT" 0, "WONK" 0;'
    ]
  }
];

function build() {
  var out = [];
  out.push('/*');
  out.push(' * fonts.css: GENERATED by tools/build-fonts.js. Do not edit by hand.');
  out.push(' *');
  out.push(' * The deck\'s two typefaces, embedded as data URIs so they load from file://');
  out.push(' * with no network and no font files to carry around. Both are open-licensed:');
  FACES.forEach(function (f) { out.push(' *   ' + f.licence); });
  out.push(' * Licence text: https://openfontlicense.org (not fetched; named for the record).');
  out.push(' */');
  out.push('');
  FACES.forEach(function (f) {
    var src = path.join(FONT_DIR, f.file);
    var buf = fs.readFileSync(src);
    if (buf.slice(0, 4).toString('latin1') !== 'wOF2') {
      throw new Error(f.file + ' is not a woff2 file');
    }
    out.push('/* ' + f.licence + ' Source: theme/fonts/' + f.file + ' (' + buf.length + ' bytes) */');
    out.push('@font-face {');
    out.push('  font-family: "' + f.family + '";');
    f.css.forEach(function (line) { out.push('  ' + line); });
    out.push('  src: url("data:font/woff2;base64,' + buf.toString('base64') + '") format("woff2");');
    out.push('}');
    out.push('');
  });
  return out.join('\n');
}

function main() {
  var css = build();
  var bytes = Buffer.byteLength(css, 'utf8');
  if (bytes > LIMIT) {
    console.error('FAIL fonts.css would be ' + bytes + ' bytes, over the 1.5 MB limit');
    process.exit(1);
  }
  if (process.argv.indexOf('--check') !== -1) {
    var current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== css) {
      console.error('FAIL deck/theme/fonts.css is out of date: run node tools/build-fonts.js');
      process.exit(1);
    }
    console.log('ok   deck/theme/fonts.css is up to date (' + bytes + ' bytes)');
    return;
  }
  fs.writeFileSync(OUT, css);
  console.log('wrote deck/theme/fonts.css  ' + bytes + ' bytes  (' + (bytes / 1024).toFixed(0) + ' KB, limit 1536 KB)');
  FACES.forEach(function (f) { console.log('  ' + f.family + '  <-  theme/fonts/' + f.file); });
}

main();
